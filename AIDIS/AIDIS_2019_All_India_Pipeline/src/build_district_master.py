# Project folder:
# D:\AIDIS\AIDIS_All_India_Pipeline
PROJECT_ROOT = Path(__file__).resolve().parents[1]

# Original friend's AIDIS folder:
# D:\AIDIS
AIDIS_ROOT = PROJECT_ROOT.parent


# Friend's national output file.
NATIONAL_FILE = AIDIS_ROOT / "AIDIS_Final_Client.csv"

# State master that we created in the previous step.
STATE_MASTER_FILE = PROJECT_ROOT / "config" / "state_master.csv"

# This file will be generated by this script.
OUTPUT_FILE = PROJECT_ROOT / "config" / "district_master_template.csv"


# ============================================================
# HELPER FUNCTION
# ============================================================

def normalize_code(value, width):
    """
    Convert a numeric/string code into a zero-padded string.

    Examples:
        1       -> "01"   when width=2
        "1"     -> "01"
        "01"    -> "01"
        27.0    -> "27"

        101     -> "0101" when width=4
        2701    -> "2701"
    """

    if pd.isna(value):
        return None

    value = str(value).strip()

    # Pandas may sometimes read integer-like values as:
    # 27.0
    # 2701.0
    if value.endswith(".0"):
        value = value[:-2]

    if value == "":
        return None

    return value.zfill(width)


# ============================================================
# MAIN PROCESS
# ============================================================

def main():

    print("=" * 70)
    print("AIDIS DISTRICT MASTER BUILDER")
    print("=" * 70)

    # --------------------------------------------------------
    # STEP 1: Check required files
    # --------------------------------------------------------

    if not NATIONAL_FILE.exists():
        raise FileNotFoundError(
            f"\nNational AIDIS file not found:\n{NATIONAL_FILE}"
        )

    if not STATE_MASTER_FILE.exists():
        raise FileNotFoundError(
            f"\nState master file not found:\n{STATE_MASTER_FILE}"
        )

    print("\nInput files found successfully.")

    print("\nNational file:")
    print(NATIONAL_FILE)

    print("\nState master:")
    print(STATE_MASTER_FILE)

    # --------------------------------------------------------
    # STEP 2: Read state master
    # --------------------------------------------------------

    state_master = pd.read_csv(
        STATE_MASTER_FILE,
        dtype=str
    )

    required_state_columns = {
        "State_ID",
        "State_Name",
        "File_Name"
    }

    missing_state_columns = (
        required_state_columns - set(state_master.columns)
    )

    if missing_state_columns:
        raise ValueError(
            "state_master.csv is missing columns: "
            f"{sorted(missing_state_columns)}"
        )

    state_master["State_ID"] = (
        state_master["State_ID"]
        .apply(lambda x: normalize_code(x, 2))
    )

    print(
        f"\nStates/UTs loaded from state_master.csv: "
        f"{len(state_master)}"
    )

    # --------------------------------------------------------
    # STEP 3: Read only required columns from national file
    #
    # The national file is large, so we do not need to load
    # every one of its 22/23 columns.
    # --------------------------------------------------------

    national = pd.read_csv(
        NATIONAL_FILE,
        usecols=["State_ID", "District_ID"],
        dtype=str,
        low_memory=False
    )

    print(
        f"\nRows read from AIDIS_Final_Client.csv: "
        f"{len(national):,}"
    )

    # --------------------------------------------------------
    # STEP 4: Normalize State_ID
    # --------------------------------------------------------

    national["State_ID"] = (
        national["State_ID"]
        .apply(lambda x: normalize_code(x, 2))
    )

    # --------------------------------------------------------
    # STEP 5: Normalize District_ID
    #
    # Example:
    #
    #   101  -> 0101
    #   2701 -> 2701
    #
    # We always preserve it as a 4-character string.
    # --------------------------------------------------------

    national["District_ID"] = (
        national["District_ID"]
        .apply(lambda x: normalize_code(x, 4))
    )

    # --------------------------------------------------------
    # STEP 6: Remove All-India rows
    #
    # State_ID 00 represents All India and is not a state
    # district mapping.
    # --------------------------------------------------------

    national = national[
        national["State_ID"].notna()
    ].copy()

    national = national[
        national["State_ID"] != "00"
    ].copy()

    # --------------------------------------------------------
    # STEP 7: Remove rows without a real district
    # --------------------------------------------------------

    national = national[
        national["District_ID"].notna()
    ].copy()

    national = national[
        ~national["District_ID"].isin(
            [
                "0000",
                "000",
                "00",
                "0"
            ]
        )
    ].copy()

    # --------------------------------------------------------
    # STEP 8: Keep only district codes belonging to their
    # corresponding state.
    #
    # Example:
    #
    # State_ID    = 27
    # District_ID = 2701
    #
    # Valid because 2701 starts with 27.
    # --------------------------------------------------------

    national = national[
        national.apply(
            lambda row: (
                row["District_ID"].startswith(
                    row["State_ID"]
                )
            ),
            axis=1
        )
    ].copy()

    # --------------------------------------------------------
    # STEP 9: Get only unique State-District combinations
    # --------------------------------------------------------

    district_master = (
        national[
            [
                "State_ID",
                "District_ID"
            ]
        ]
        .drop_duplicates()
        .sort_values(
            [
                "State_ID",
                "District_ID"
            ]
        )
        .reset_index(drop=True)
    )

    # --------------------------------------------------------
    # STEP 10: Create local District_Code
    #
    # Examples:
    #
    # 2701 -> 01
    # 2702 -> 02
    # 2735 -> 35
    #
    # 0101 -> 01
    # --------------------------------------------------------

    district_master["District_Code"] = (
        district_master["District_ID"].str[-2:]
    )

    # --------------------------------------------------------
    # STEP 11: Add State Name from state_master.csv
    # --------------------------------------------------------

    state_lookup = dict(
        zip(
            state_master["State_ID"],
            state_master["State_Name"]
        )
    )

    district_master["State_Name"] = (
        district_master["State_ID"]
        .map(state_lookup)
    )

    # --------------------------------------------------------
    # STEP 12: Check for unknown state codes
    # --------------------------------------------------------

    unknown_states = district_master[
        district_master["State_Name"].isna()
    ]

    if not unknown_states.empty:

        print("\nWARNING: Unknown State_ID values found:")

        print(
            unknown_states[
                [
                    "State_ID",
                    "District_ID"
                ]
            ]
            .drop_duplicates()
            .to_string(index=False)
        )

    # --------------------------------------------------------
    # STEP 13: Arrange columns
    # --------------------------------------------------------

    district_master = district_master[
        [
            "State_ID",
            "State_Name",
            "District_Code",
            "District_ID"
        ]
    ]

    # --------------------------------------------------------
    # STEP 14: Add columns that we will populate later
    # --------------------------------------------------------

    district_master["District_Name"] = ""

    district_master["Source"] = ""

    district_master["Status"] = "UNMAPPED"

    district_master["Notes"] = ""

    # --------------------------------------------------------
    # STEP 15: Check duplicate District_ID
    # --------------------------------------------------------

    duplicate_districts = district_master[
        district_master.duplicated(
            subset=["District_ID"],
            keep=False
        )
    ]

    if not duplicate_districts.empty:

        print("\nWARNING: Duplicate District_ID values found:")

        print(
            duplicate_districts.to_string(
                index=False
            )
        )

    # --------------------------------------------------------
    # STEP 16: Save the District Master template
    # --------------------------------------------------------

    OUTPUT_FILE.parent.mkdir(
        parents=True,
        exist_ok=True
    )

    district_master.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8-sig"
    )

    # --------------------------------------------------------
    # STEP 17: Display summary
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("DISTRICT MASTER TEMPLATE CREATED")
    print("=" * 70)

    print(
        f"\nTotal unique districts found: "
        f"{len(district_master):,}"
    )

    print(
        f"\nOutput file:\n{OUTPUT_FILE}"
    )

    # --------------------------------------------------------
    # Show district count for every state
    # --------------------------------------------------------

    district_counts = (
        district_master
        .groupby(
            [
                "State_ID",
                "State_Name"
            ],
            dropna=False
        )
        .size()
        .reset_index(
            name="District_Count"
        )
    )

    print("\nDistrict count by State/UT:\n")

    print(
        district_counts.to_string(
            index=False
        )
    )

    print("\n" + "=" * 70)
    print("SUCCESS")
    print("=" * 70)

    print(
        "\nNext we will populate District_Name "
        "and verify every district code."
    )


# ============================================================
# PROGRAM ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()